"""Parity check: training-side year accounting vs eval-side replay.

Drives ONE fixed route sequence (generated by the greedy baseline) through both
the eval path and a faithful reconstruction of the training path, then asserts
the per-year welfare cost C(s_y) and post-growth activity sum(x_y) match.

WHY THIS EXISTS
---------------
train_rl._collect_episode and eval_rl/multi_year_mdp advance the world through
two independent code paths:

  * eval  : CityBuilderEnv.step -> step_world(...)        ; _welfare_cost builds
            a fresh RouteGenBatchState with n_routes_to_plan = (routes built so
            far)  [multi_year_mdp.py:199-214]
  * train : _advance_year -> dyn.step(x, state.transit_times)  ; cost read off
            the LIVE state whose n_routes_to_plan = T (full horizon)
            [train_rl.py:78-86, 181]

The ONLY intended differences are (a) n_routes_to_plan sizing (T vs cumulative)
and (b) dyn.step vs step_world. If welfare_cost or sum(x) diverge, the policy is
optimizing a different MDP than it is scored on -- a prime suspect for "trains
but never reaches greedy". This script reuses the SAME primitives as eval
(RouteGenBatchState + add_new_routes + cost_obj) on the train side and differs
ONLY in those two known axes, so any reported gap is attributable to them.

This enforces the contract the TOP-32 plan promises in validation step 2 and the
comment at train_rl.py:139-141.

RUN (from repo root, in the torch-2.8 / PyG-2.7 / py3.12 env):
    python -m learning.city_builder.parity_train_vs_eval \
        --config-name=ppo_citybuilder_mumford0
    # optional: --config-name=ppo_citybuilder_mandl, or override city_builder.alpha=...
"""
from __future__ import annotations

import copy

import hydra
import torch
from omegaconf import DictConfig
from torch_geometric.loader import DataLoader

from torch_utils import get_batch_tensor_from_routes
from simulation.transit_time_estimator import MyCostModule, RouteGenBatchState
from simulation.citygraph_dataset import get_dataset_from_config

from learning.city_builder.multi_year_mdp import (
    run_episode, greedy_policy,
)
from learning.city_builder.eval_rl import _make_env, replay_metrics
from learning.city_builder.train_rl import (
    horizon_T, _make_episode_state, _squeeze_b1, _write_gravity_demand_b1,
)

# Match tolerance: costs are ~O(100), activity sums ~O(1e3-1e4). Relative tol is
# the meaningful test; absolute floor guards the near-zero deltas.
RTOL = 1e-4
ATOL = 1e-3


def _cumulative_net(routes, upto_year, min_len, max_len):
    """(1,R,L) batch tensor for all valid routes built through `upto_year`, or
    None if no route has been built yet (empty-network year)."""
    built = [r for r in routes[: upto_year + 1]
             if r is not None and len(r) >= min_len]
    if not built:
        return None
    return get_batch_tensor_from_routes([built], max_route_len=max_len)


def _train_side_trajectory(cfg, cost_obj, routes, device):
    """Reconstruct the per-year (welfare_cost, sum_x) the TRAINING rollout would
    record for `routes`, reusing train_rl's own episode setup + transition.

    Faithful to train_rl._collect_episode's ordering:
        advance dynamics (dyn.step on the network's transit accessibility)
        -> write post-growth gravity demand -> read level cost C(s_y).
    n_routes_to_plan is fixed at T, exactly as the live training state.
    """
    T = horizon_T(cfg)
    beta = cfg.city_builder.beta_gravity
    min_len = int(cfg.eval.min_route_len)
    max_len = int(cfg.eval.max_route_len)

    # Same template + dynamics the trainer builds (cfg-sourced beta/cap/seed).
    _dataset = get_dataset_from_config(cfg.eval.dataset)
    template = next(iter(DataLoader(_dataset, batch_size=1)))
    state, dyn, x_0, _cw = _make_episode_state(template, cost_obj, T, cfg, device)
    data = state.graph_data          # gravity demand under x_0 already written
    x = x_0.clone()

    costs, xs = [], []
    with torch.no_grad():
        for y in range(len(routes)):
            net = _cumulative_net(routes, y, min_len, max_len)
            n_built = 0 if net is None else net.shape[1]

            # transit accessibility off the current network. n_routes_to_plan
            # here is irrelevant to transit (confirmed: it is topology/traveltime
            # only); keep T to mirror _advance_year reading the live state.
            st = RouteGenBatchState(data, cost_obj, n_routes_to_plan=T,
                                    min_route_len=min_len, max_route_len=max_len)
            if net is not None:
                st.add_new_routes(net)
            transit = _squeeze_b1(st.transit_times)

            # advance one year of induced demand (mirrors _advance_year)...
            x, _ = dyn.step(x, transit)
            _write_gravity_demand_b1(data, x, beta)   # post-growth demand

            # ...then read the level cost under the new demand, sized to the
            # REALIZED network (mirrors the fixed train_rl._realized_network_cost
            # and eval_rl._welfare_cost): n_routes_to_plan = routes built so far.
            st2 = RouteGenBatchState(data, cost_obj,
                                     n_routes_to_plan=max(n_built, 1),
                                     min_route_len=min_len, max_route_len=max_len)
            if net is not None:
                st2.add_new_routes(net)
            costs.append(float(cost_obj(st2).cost.item()))
            xs.append(float(x.sum().item()))
    return costs, xs


@hydra.main(version_base=None, config_path="../../cfg",
            config_name="ppo_citybuilder_mumford0")
def main(cfg: DictConfig):
    device = "cuda" if torch.cuda.is_available() else "cpu"
    cost_obj = MyCostModule(symmetric_routes=True)

    # 1) Generate ONE fixed route sequence via the greedy baseline, recording
    #    each year's action AND the eval-side trajectory in the same pass.
    env = _make_env(cfg)
    routes = []

    def recording_greedy(e):
        a = greedy_policy(e)
        routes.append(a)
        return a

    print("\n=== EVAL-side rollout (greedy baseline) ===")
    recs = run_episode(env, recording_greedy, verbose=True)
    eval_cost = [r["welfare_cost"] for r in recs]
    eval_x = [r["sum_activity"] for r in recs]

    # 2) Replay the SAME routes through the train-side accounting.
    print("\n=== TRAIN-side reconstruction (same routes) ===")
    train_cost, train_x = _train_side_trajectory(cfg, cost_obj, routes, device)

    # 3) Per-year comparison.
    print("\n year |     eval C |    train C |     dC | "
          "  eval sum(x) | train sum(x) |   dx")
    print(" -----+------------+------------+--------+"
          "--------------+--------------+--------")
    ok = True
    for y in range(len(routes)):
        ec, tc = eval_cost[y], train_cost[y]
        ex, tx = eval_x[y], train_x[y]
        dc, dx = tc - ec, tx - ex
        cost_ok = abs(dc) <= ATOL + RTOL * abs(ec)
        x_ok = abs(dx) <= ATOL + RTOL * abs(ex)
        ok = ok and cost_ok and x_ok
        flag = "" if (cost_ok and x_ok) else "  <-- MISMATCH"
        print(f" {y+1:4d} | {ec:10.4f} | {tc:10.4f} | {dc:+6.3f} | "
              f"{ex:12.1f} | {tx:12.1f} | {dx:+6.1f}{flag}")

    # 4) Integrated-welfare contract (train_rl.py:139-141 / TOP-32 validation #2).
    eval_int = replay_metrics(routes, cfg)["integrated"]   # -sum_t C(s_t)
    train_int = -sum(train_cost)
    int_ok = abs(train_int - eval_int) <= ATOL + RTOL * abs(eval_int)
    print(f"\n integrated welfare  eval={eval_int:.4f}  train={train_int:.4f}  "
          f"d={train_int - eval_int:+.4f}  {'OK' if int_ok else 'MISMATCH'}")

    print("\n" + ("PARITY OK -- train and eval score routes identically."
                  if (ok and int_ok) else
                  "PARITY FAILED -- train/eval diverge. The most likely cause is "
                  "n_routes_to_plan sizing (T vs cumulative) feeding the cost / "
                  "transit module differently; see _welfare_cost + _transit_times."))
    assert ok and int_ok, "train-vs-eval parity mismatch (see table above)"


if __name__ == "__main__":
    main()
